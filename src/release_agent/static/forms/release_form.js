import { escapeHtml as esc, shortName } from '../core/format.js';
import { buildSummary, forRelease, releaseRouteText } from '../core/queue.js';
import { CHIPS, DF_DRAFT_FIELDS, PROSE_FIELDS, canReplace, chipState, itemsKey, monoReleaseNote } from '../core/chg.js';
import { getContext, QUEUE_PATH, releaseDefaults, releaseDraft, whoami } from '../api.js';
import { sendMessage } from '../chat.js';
import { ctxNote, labeledField, opening, withDismiss } from './common.js';

// ---- CARE / DF release (live model) --------------------------------------
// One form, two flavors, same backend pipeline (release_details.json → the
// repo's updater script → preview → CONFIRM):
//   CARE Release: helm charts with per-service PRL1-only / DF-image flags.
//   DF Release:   Dataflow images only — every artifact is auto-flagged
//                 df_images (excluded from all helm deploy workflows), so
//                 there are no per-service checkboxes to get wrong.
// In mono mode (CARE_RELEASE_MODE=mono) a CARE release is instead one
// committed file in the mono repo, raised as a PR a person merges. The form
// and its payload are the same; the header, the repo, the summary and the
// drafting differ — the prose opens already drafted, each field marked with
// where its text came from. DF, and CARE in fileset mode, keep the draft
// button and the wording they always had.
// The queue pre-fill is flavor-aware: DF sees only df-flagged intents, CARE
// sees the rest.
export async function showReleaseForm(kind) {
    const isDf = kind === 'df';
    // Queue context first: the accumulated "add me to the next release" intents
    // pre-fill the artifact list, and the default deployment repo pre-fills the
    // target repo field.
    const _ph = opening(isDf ? 'DF Release' : 'CARE Release');
    const qctx = await getContext(QUEUE_PATH,
        { queue: [], default_repo: '', df_default_repo: '',
          care_release_mode: 'fileset', care_release_repo: '', care_release_file: '' });
    _ph.remove();
    const mono = !isDf && qctx.care_release_mode === 'mono';
    // The two releases are independent: a DF release carries only df_only items
    // and is raised in its own repo (DF_RELEASE_REPO), so it neither picks up
    // CARE artifacts nor targets the CARE repo.
    const otherQueued = forRelease(qctx.queue, !isDf).length;
    qctx.queue = forRelease(qctx.queue, isDf);
    const targetRepo = isDf ? (qctx.df_default_repo || qctx.default_repo)
        : (mono && qctx.care_release_repo) || qctx.default_repo;

    const chat = document.getElementById('chat');
    const wrap = document.createElement('div');
    wrap.className = 'message bot interrupt-box rounded-2xl p-4 text-sm';
    wrap.innerHTML = isDf
        ? '<div class="mb-1 font-semibold flex items-center gap-2 text-sky-300">' +
          '<i class="fa-solid fa-water"></i> DF Release</div>' +
          '<div class="text-slate-400 text-xs mb-3">Dataflow images + change request → the release file-set ' +
          '(artefact.json + SDLC governance), generated by the repo\'s updater script. DF images are ' +
          'excluded from the helm deploy workflows — they ship via the Dataflow dispatch. ' +
          'Raised in its own repo, separately from the CARE release. ' +
          'You\'ll see the full diff and RCTL timeline before anything is pushed.</div>'
        : '<div class="mb-1 font-semibold flex items-center gap-2 text-emerald-300">' +
          '<i class="fa-solid fa-box-open"></i> CARE Release</div>' +
          '<div class="text-slate-400 text-xs mb-3">' + (mono
              ? esc(monoReleaseNote(qctx.care_release_file, qctx.care_release_repo))
              : 'Artifacts + change request → the release file-set ' +
                '(artefact.json, SDLC governance, per-env workflows), generated by the repo\'s updater script. ' +
                'You\'ll see the full diff and RCTL timeline before anything is pushed.') + '</div>';

    const relNote = ctxNote(qctx, 'the intake queue'); if (relNote) wrap.appendChild(relNote);
    // An empty checklist looked like a broken form. Say why it is empty — and
    // when the other release has items, say so, because that is usually the
    // answer ("I queued it" — as CARE, not Dataflow).
    if (!relNote && !(qctx.queue || []).length) {
        const empty = document.createElement('div');
        empty.className = 'text-[11px] text-slate-400 border border-slate-700 rounded-lg px-3 py-2 mb-2';
        const kind = isDf ? 'Dataflow' : 'CARE';
        const other = isDf ? 'CARE' : 'Dataflow';
        empty.innerHTML = '<i class="fa-solid fa-circle-info mr-1 text-slate-500"></i>' +
            'Nothing is queued for the ' + kind + ' release yet' +
            (otherQueued ? ' — ' + otherQueued + ' item' + (otherQueued === 1 ? ' is' : 's are') +
                ' queued for the ' + other + ' release' : '') + '. ' +
            'Developers queue ' + (isDf ? 'Dataflow images' : 'charts') + ' with <b>Add to next release</b>' +
            (isDf ? ', ticking <b>Dataflow</b>' : ', ticking <b>CARE</b>') +
            '. You can still type artifacts below.';
        wrap.appendChild(empty);
    }

    const grid = document.createElement('div');
    grid.className = 'grid gap-2 mb-2';
    const mk = (labelText, spec) => labeledField(grid, Object.assign({ label: labelText }, spec));
    const nameEl = mk('Release name *', { id: 'rel-name', placeholder: 'e.g. July 20th 2026 : Release 31' });
    const startEl = mk('Start *', { id: 'rel-start', type: 'datetime-local' });
    const endEl = mk('End *', { id: 'rel-end', type: 'datetime-local' });
    const initEl = mk('Change initiator (email) *', { id: 'rel-initiator', placeholder: 'you@company.com' });
    const sumEl = mk('Change summary *', { id: 'rel-summary' });
    const descEl = mk('Change description', { id: 'rel-desc', tag: 'textarea' });
    const reasonEl = mk('Change reason', { id: 'rel-reason', tag: 'textarea' });
    const riskEl = mk('Associated risk', { id: 'rel-risk', tag: 'textarea' });
    const consEl = mk('Consequence', { id: 'rel-consequence', tag: 'textarea' });
    const impactEl = mk('User/service impact', { id: 'rel-impact', tag: 'textarea' });
    const repoEl = mk('Deployment repo (owner/repo) *',
        { id: 'rel-repo', placeholder: 'e.g. my-org/deployment-repo' });
    repoEl.value = targetRepo || '';
    // Mono mode: the release file lives in one configured repo, so the field
    // shows it instead of inviting another.
    if (mono && qctx.care_release_repo) {
        repoEl.readOnly = true;
        repoEl.classList.add('opacity-70');
        repoEl.title = 'CARE releases are raised in this repo (CARE_RELEASE_REPO)';
    }
    const artEl = mk(
        isDf ? 'DF images * — one per line (full URL or name:version); all excluded from helm deploys'
             : 'Artifacts * — one per line (full URL or name:version)',
        { id: 'rel-artifacts', tag: 'textarea',
          placeholder: isDf ? 'order-enrichment:1.4.2\nhttps://artifactory…/df-position-agg:2.1.0'
                            : 'acme-workflow-service:4.0.66\nhttps://artifactory…/acme-risk-fetcher:4.0.153' });
    artEl.rows = 5; artEl.spellcheck = false; artEl.classList.add('font-mono');
    wrap.appendChild(grid);

    const artifactLines = () => artEl.value.split('\n').map(l => l.trim()).filter(Boolean);

    // Every change-request field except start/end is filled from facts
    // (POST /api/release-defaults: queue items, JIRA keys, build verification,
    // the repo's last release number) and recomputed when the items or the
    // start date change. A field only follows the defaults while it still holds
    // the last value they put there — any human edit is kept.
    const autoVals = {};
    const fillAuto = (el, key, value) => {
        if (value == null) return;
        if (!el.value.trim() || el.value === autoVals[key]) { el.value = value; autoVals[key] = value; }
    };

    // Mono mode: the release file's summary IS the release name, so the name is
    // the summary's one writer — it follows every name change until the person
    // edits the summary itself.
    let summaryAuto = null;
    const syncSummary = () => {
        if (!canReplace(sumEl.value, summaryAuto)) return;
        sumEl.value = nameEl.value;
        summaryAuto = { value: nameEl.value, source: 'team' };
    };
    if (mono) nameEl.addEventListener('input', syncSummary);

    // Mono mode's prose fields (core/chg.js): one automatic writer per field at
    // a time — the AI draft while it was made for the items the form holds
    // (draftFor), otherwise the defaults' standard wording — and neither
    // replaces what the person typed. A chip beside each label says where its
    // text came from.
    // DF drafts like CARE in mono mode (auto on open, chips, Regenerate), and
    // its summary as well; CARE in fileset mode keeps the button draft.
    const autoDraft = mono || isDf;
    const draftFields = isDf ? DF_DRAFT_FIELDS : PROSE_FIELDS;
    const proseEls = { change_summary: sumEl, change_description: descEl, change_reason: reasonEl,
                       associated_risk: riskEl, consequence: consEl, user_service_impact: impactEl };
    const proseAuto = {};                 // field -> {value, source}: the last automatic write
    let draftFor = null;                  // itemsKey of the items the draft in the fields describes
    const chips = {};
    const CHIP_TONE = { ai: 'bg-emerald-500/15 text-emerald-300', team: 'bg-slate-700 text-slate-300',
                        edited: 'bg-slate-800 text-sky-300', fallback: 'bg-amber-500/15 text-amber-300' };
    const paintChip = (field) => {
        const chip = chips[field];
        if (!chip) return;
        const state = chipState(proseEls[field].value, proseAuto[field]);
        chip.className = state ? 'text-[10px] px-1.5 py-0.5 rounded leading-none font-normal ' +
            'whitespace-nowrap select-none ' + CHIP_TONE[state] : 'hidden';
        chip.textContent = state ? CHIPS[state].label : '';
        chip.title = state ? CHIPS[state].title : '';
    };
    const writeProse = (field, value, source) => {
        const el = proseEls[field];
        if (value != null && canReplace(el.value, proseAuto[field])) {
            el.value = value;
            proseAuto[field] = { value, source };
        }
        paintChip(field);
    };
    if (autoDraft) {
        draftFields.forEach(field => {
            const el = proseEls[field];
            const label = el.parentElement && el.parentElement.querySelector('label');
            if (label) {
                label.classList.remove('block');
                label.classList.add('flex', 'items-center', 'gap-1.5');
                chips[field] = document.createElement('span');
                chips[field].className = 'hidden';
                label.appendChild(chips[field]);
            }
            el.addEventListener('input', () => paintChip(field));
        });
    }

    // The draft controls. Shown only when something is queued: a draft
    // summarises the developers' queue entries, and typed lines carry none.
    const draftRow = document.createElement('div');
    draftRow.className = 'flex items-center gap-2 mb-2';
    const draftBtn = document.createElement('button');
    draftBtn.type = 'button';
    draftBtn.className = 'border border-slate-600 hover:border-emerald-400/60 rounded-lg ' +
        'px-2.5 py-1 text-[11px] text-slate-300 flex items-center gap-1.5';
    const draftMsg = document.createElement('span');
    draftMsg.className = 'text-[11px] text-slate-500';
    draftRow.appendChild(draftBtn); draftRow.appendChild(draftMsg);
    const draftNote = (text, tone) => {
        draftMsg.className = 'text-[11px] ' + (tone || 'text-slate-500');
        draftMsg.textContent = text;
    };

    const localToday = () => {
        const d = new Date();
        return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
    };
    // The release number is looked up once (the first call reads the repo's
    // release PRs — slow, several GitHub pages); every later recompute sends it
    // back so a date change never waits on GitHub.
    let defaultsTimer = null, defaultsSeq = 0, defaultsInflight = null, knownNumber = null;
    const runDefaults = async () => {
        const seq = ++defaultsSeq;
        let res = null;
        try {
            res = await releaseDefaults({
                artifacts: artifactLines(),
                kind: isDf ? 'df' : 'care',
                repo: repoEl.value.trim(),
                date: startEl.value ? startEl.value.slice(0, 10) : localToday(),
                number: knownNumber,
            });
        } catch (e) { return; }                       // defaults are a convenience
        if (res && res.number) knownNumber = res.number;
        if (seq !== defaultsSeq || !res || !res.ok) return;   // a newer request won
        const f = res.fields || {};
        fillAuto(nameEl, 'name', f.release_name);
        if (!autoDraft) {
            fillAuto(sumEl, 'summary', f.change_summary);
            fillAuto(descEl, 'desc', f.change_description);
            fillAuto(reasonEl, 'reason', f.change_reason);
            fillAuto(riskEl, 'risk', f.associated_risk);
            fillAuto(consEl, 'consequence', f.consequence);
            fillAuto(impactEl, 'impact', f.user_service_impact);
            return;
        }
        if (mono) syncSummary();
        // A draft of other items no longer describes this release: the standard
        // wording takes its fields back (edits stay) until Regenerate.
        if (draftFor !== null && draftFor !== itemsKey(artifactLines())) {
            draftFor = null;
            draftNote('The items changed since the AI draft — the standard wording is back. ' +
                      'Regenerate to draft these items.');
        }
        if (draftFor === null) draftFields.forEach(field => writeProse(field, f[field], 'team'));
    };
    const refreshDefaults = () => {
        clearTimeout(defaultsTimer);
        defaultsTimer = setTimeout(() => {
            defaultsTimer = null;
            defaultsInflight = runDefaults().finally(() => { defaultsInflight = null; });
        }, 250);
    };
    // Before a submit reads the fields: finish any recompute still pending, so
    // setting the start date and clicking Create at once cannot send the
    // previous date in the name. Returns false if it has not finished within
    // the wait — the submit then stops rather than send fields it knows are
    // about to change.
    const settleDefaults = async () => {
        if (defaultsTimer) { clearTimeout(defaultsTimer); defaultsTimer = null;
                             defaultsInflight = runDefaults().finally(() => { defaultsInflight = null; }); }
        if (!defaultsInflight) return true;
        const done = await Promise.race([defaultsInflight.then(() => true),
                                         new Promise(r => setTimeout(() => r(false), 8000))]);
        return done;
    };
    // The initiator is the person creating the release: remembered from the
    // last one they created, else the email they queue with.
    try { initEl.value = localStorage.getItem('release_initiator') || localStorage.getItem('queue_email') || ''; } catch (e) {}
    // Signed in: default to the verified user. Still editable — a change can be
    // raised on someone's behalf — but only replaces a value nobody typed here.
    whoami().then(who => {
        if (who && who.signed_in && who.email && !initEl.dataset.edited) initEl.value = who.email;
    });
    initEl.addEventListener('input', () => { initEl.dataset.edited = '1'; });
    const autoNote = document.createElement('div');
    autoNote.className = 'text-[10px] text-slate-500 -mt-1 mb-2';
    autoNote.textContent = 'Filled from the queue and the release history — set the start and end, ' +
        'review the rest. Anything you edit is kept.';
    wrap.appendChild(autoNote);
    artEl.addEventListener('input', refreshDefaults);
    startEl.addEventListener('change', refreshDefaults);
    repoEl.addEventListener('change', refreshDefaults);

    // Routing per service is READ from the queue — the developer chose PRD /
    // PRL1 (and CARE vs DF) with the tick boxes when they queued it, so DevOps
    // is not asked to enter it again. A CARE release never carries DF images
    // (they have their own release), so there is no DF box here either. Only a
    // chart typed straight into the form has no queued choice to read; that is
    // the one case that still offers PRL1-only.
    const flagsHdr = document.createElement('div');
    flagsHdr.className = 'text-[11px] text-slate-400 mb-1';
    flagsHdr.textContent = isDf ? 'Pipelines (from the queue):' : 'Routing (from the queue):';
    const flags = document.createElement('div');
    flags.className = 'mb-2 space-y-1';
    wrap.appendChild(flagsHdr); wrap.appendChild(flags);

    const queuedByName = {};
    (qctx.queue || []).forEach(q => { queuedByName[q.artifact_name] = q; });
    const manualPrl1 = new Set();

    // A typed artifact line is either name:version or a full registry URL. The
    // trailing slashes come off without a regex (parsing paths are tokenizers
    // here — the house pattern is state.js's API_BASE).
    const parseNames = () => artEl.value.split('\n').map(l => l.trim()).filter(Boolean).map(l => {
        while (l.endsWith('/')) l = l.slice(0, -1);
        const last = l.split('/').pop();
        const i = last.indexOf(':');
        return i > 0 ? last.slice(0, i) : null;
    }).filter(Boolean);

    const routeText = (q) => releaseRouteText(q, isDf);

    const renderFlags = () => {
        flags.innerHTML = '';
        const seen = new Set();
        parseNames().forEach(n => {
            if (seen.has(n)) return; seen.add(n);
            const q = queuedByName[n];
            const row = document.createElement('div');
            row.className = 'flex items-center gap-3 text-[11px] font-mono';
            const name = '<span class="w-44 shrink-0 truncate text-slate-300">' + esc(n) + '</span>';
            if (q) {
                row.innerHTML = name + '<span class="flex-1 text-slate-400">' + esc(routeText(q)) + '</span>' +
                    '<span class="text-slate-600">from the queue</span>';
            } else if (isDf) {
                row.innerHTML = name + '<span class="flex-1 text-slate-500">not queued — ' +
                    'pipelines chosen at deploy time</span>';
            } else {
                row.innerHTML = name + '<span class="flex-1 text-amber-300/80">not queued — no routing ' +
                    'choice to read</span><label class="flex items-center gap-1 text-slate-400">' +
                    '<input type="checkbox" data-prl1-manual="' + esc(n) + '"' +
                    (manualPrl1.has(n) ? ' checked' : '') + '> PRL1-only</label>';
                row.querySelector('input').addEventListener('change', (e) => {
                    if (e.target.checked) manualPrl1.add(n); else manualPrl1.delete(n);
                });
            }
            flags.appendChild(row);
        });
        flagsHdr.style.display = seen.size ? '' : 'none';
    };
    // What the release is raised with: the queued choice, else the manual box.
    const prl1Names = () => isDf ? [] : Array.from(new Set(parseNames())).filter(n =>
        queuedByName[n] ? !!queuedByName[n].prl1_only : manualPrl1.has(n));
    artEl.addEventListener('input', renderFlags);
    renderFlags();

    // Thursday pre-fill: the intake queue arrives as a checklist — untick an
    // item to defer it (it stays queued for the next release). Ticked items
    // fill the artifact list; their routing is read from the queue above.
    if ((qctx.queue || []).length) {
        const qBox = document.createElement('div');
        qBox.className = 'border border-emerald-700/40 bg-emerald-500/5 rounded-lg px-3 py-2 mb-2';
        qBox.innerHTML = '<div class="text-[11px] text-emerald-300 mb-1"><i class="fa-solid fa-cart-plus mr-1"></i>' +
            'Queued for this release (' + qctx.queue.length + ') — untick to defer to the next one</div>';
        const applyItem = (q, on) => {
            const line = q.artifact_name + ':' + q.artifact_version;
            const lines = artEl.value.split('\n').map(l => l.trim()).filter(Boolean)
                .filter(l => l.split('/').pop().indexOf(q.artifact_name + ':') !== 0);
            if (on) lines.push(line);
            artEl.value = lines.join('\n');
            renderFlags();
            refreshDefaults();
        };
        qctx.queue.forEach(q => {
            const row = document.createElement('label');
            row.className = 'flex items-center gap-2 text-[11px] text-slate-300 font-mono py-0.5 cursor-pointer';
            const cb = document.createElement('input');
            cb.type = 'checkbox'; cb.checked = true; cb.dataset.q = q.artifact_name;
            // Same wording as the queue table's Build column (core/queue.js).
            // Nothing is shown for 'unknown': a build nobody checked must not
            // look like a build that failed its check.
            const bs = buildSummary(q);
            const badge = bs.state === 'verified'
                ? ' <i class="fa-solid fa-circle-check text-emerald-400" title="' + esc(bs.title) + '"></i>'
                : bs.state === 'unverified'
                    ? ' <i class="fa-solid fa-triangle-exclamation text-amber-400" title="' + esc(bs.title) + '"></i>'
                    : '';
            const span = document.createElement('span');
            span.className = 'flex-1 truncate';
            span.innerHTML = esc(q.artifact_name) + ':' + esc(q.artifact_version) + badge +
                (q.jira_ticket ? ' <span class="text-amber-300/80">' + esc(q.jira_ticket) + '</span>' : '') +
                (q.prl1_only ? ' <span class="text-violet-400">PRL1</span>' : '') +
                (q.df_only ? ' <span class="text-sky-400">DF</span>' : '');
            const tip = [q.change_details, q.note].filter(Boolean).join(' · ');
            if (tip) span.title = tip + ' — ' + (q.requested_by || '');
            const who = document.createElement('span');
            who.className = 'text-slate-600 truncate';
            who.textContent = shortName(q.requested_by);
            cb.addEventListener('change', () => applyItem(q, cb.checked));
            row.appendChild(cb); row.appendChild(span); row.appendChild(who);
            qBox.appendChild(row);
        });
        wrap.insertBefore(qBox, grid);
        qctx.queue.forEach(q => applyItem(q, true));
        wrap.insertBefore(draftRow, grid);

        if (!autoDraft) {
            // CARE in fileset mode: draft the change-request prose from
            // the ticked items' own details. Button, not automatic: it costs a
            // model call, and a governance field that fills itself silently
            // stops being read. Everything it writes stays editable and nothing
            // is submitted.
            draftBtn.innerHTML = '<i class="fa-solid fa-wand-magic-sparkles text-emerald-400"></i> Draft change request';
            draftBtn.title = 'Writes summary/reason/risk/consequence/impact from the ticked items — review before submitting';
            draftBtn.addEventListener('click', async () => {
                const ticked = qctx.queue.filter(it => {
                    const cb = qBox.querySelector('input[data-q="' + it.artifact_name + '"]');
                    return cb && cb.checked;
                }).map(it => it.artifact_name + ':' + it.artifact_version);
                if (!ticked.length) { draftMsg.textContent = 'Tick at least one item first.'; return; }
                draftBtn.disabled = true; draftMsg.textContent = 'Drafting…';
                let res = null;
                try {
                    res = await releaseDraft({ artifacts: ticked, kind: isDf ? 'df' : 'care' });
                } catch (e) { res = { ok: false, error: String(e) }; }
                draftBtn.disabled = false;
                if (!res || !res.ok) {
                    draftMsg.textContent = (res && res.error) || 'Could not draft — fill it in manually.';
                    return;
                }
                const d = res.draft || {};
                const fill = (el, v) => { if (v) el.value = v; };
                fill(sumEl, d.change_summary);
                fill(descEl, d.change_description);
                fill(reasonEl, d.change_reason);
                fill(riskEl, d.associated_risk);
                fill(consEl, d.consequence);
                fill(impactEl, d.user_impact);
                draftMsg.innerHTML = '<span class="text-amber-300">Draft from ' + res.grounded_on +
                    ' item(s) — review every field before submitting.</span>';
            });
        } else {
            // DF, and CARE in mono mode: the form opens already drafted — one model
            // call, from every artifact line (a full registry URL resolves
            // server-side), so the person can edit or just go ahead. Regenerate
            // drafts again and replaces only the fields the person has not
            // edited.
            let drafting = false;
            const requestDraft = async () => {
                if (drafting) return;
                const lines = artifactLines();
                if (!lines.length) { draftNote('Tick or type at least one artifact first.'); return; }
                const key = itemsKey(lines);
                drafting = true; draftBtn.disabled = true;
                draftNote('Drafting the change request from the queued items…');
                let res = null;
                try {
                    res = await releaseDraft({ artifacts: lines, kind: isDf ? 'df' : 'care' });
                } catch (e) {
                    res = { ok: false, error: 'Could not reach the drafting service — the standard wording stays.' };
                }
                drafting = false; draftBtn.disabled = false;
                if (!res || !res.ok) {
                    draftNote((res && res.error) || 'Could not draft — the standard wording stays.', 'text-amber-300/80');
                    return;
                }
                if (key !== itemsKey(artifactLines())) {
                    draftNote('The items changed while drafting — Regenerate to draft these items.');
                    return;
                }
                draftFor = key;
                const draft = res.draft || {}, sources = res.sources || {};
                draftFields.forEach(field => writeProse(field, draft[field], sources[field] || 'ai'));
                const n = res.grounded_on || lines.length;
                draftNote('AI draft of ' + n + ' item' + (n === 1 ? '' : 's') +
                          ' — review every field; anything you edit is kept.', 'text-amber-300');
            };
            draftBtn.innerHTML = '<i class="fa-solid fa-wand-magic-sparkles text-emerald-400"></i> Regenerate';
            draftBtn.title = 'Draft the description, reason, risk, consequence and impact again from the items ' +
                'above — fields you have edited are kept';
            draftBtn.addEventListener('click', requestDraft);
            requestDraft();       // once, as the form opens
        }
    }

    refreshDefaults();      // also when nothing is queued: name, number, wording

    const fmt = (v) => v ? v.replace('T', ' ') + (v.length === 16 ? ':00' : '') : '';

    const row = document.createElement('div');
    row.className = 'flex items-center gap-3 mt-1';
    const submit = document.createElement('button');
    submit.className = (isDf ? 'bg-sky-600 hover:bg-sky-500' : 'bg-emerald-600 hover:bg-emerald-500') +
        ' px-4 py-1.5 rounded-lg text-sm font-medium';
    submit.textContent = isDf ? 'Create DF release' : 'Create CARE release';
    const err = document.createElement('span');
    err.className = 'text-[11px] text-red-400';
    submit.addEventListener('click', async () => {
        err.textContent = '';
        if (!(await settleDefaults())) {
            err.textContent = 'Still computing the release name and wording — try again in a moment.';
            return;
        }
        const artifacts = artEl.value.split('\n').map(l => l.trim()).filter(Boolean);
        if (!nameEl.value.trim() || !startEl.value || !endEl.value || !initEl.value.trim() || !sumEl.value.trim()) {
            err.textContent = 'Release name, start, end, initiator and summary are required.'; return;
        }
        try { localStorage.setItem('release_initiator', initEl.value.trim()); } catch (e) {}
        if (!repoEl.value.trim() || repoEl.value.indexOf('/') < 1) {
            err.textContent = 'Deployment repo is required (owner/repo).'; return;
        }
        if (!artifacts.length) { err.textContent = 'At least one artifact is required.'; return; }
        if (fmt(endEl.value) <= fmt(startEl.value)) { err.textContent = 'End must be after start.'; return; }
        const payload = {
            deployment_repo: repoEl.value.trim(),
            release_name: nameEl.value.trim(),
            start_date: fmt(startEl.value),
            end_date: fmt(endEl.value),
            change_initiator: initEl.value.trim(),
            change_summary: sumEl.value.trim(),
            change_description: descEl.value.trim(),
            change_reason: reasonEl.value.trim(),
            associated_risk: riskEl.value.trim(),
            consequence: consEl.value.trim(),
            user_service_impact: impactEl.value.trim(),
            // DF release: every artifact is a Dataflow image by definition.
            prl1_only: prl1Names(),
            // A DF release is all DF images; a CARE release carries none.
            df_images: isDf ? Array.from(new Set(parseNames())) : [],
            artefact: artifacts,
            // Picks the release path server-side (CARE: SIT→UAT→PRD, or the one
            // mono-repo file in mono mode; DF: its own chain).
            release_kind: isDf ? 'df' : 'care',
        };
        sendMessage(JSON.stringify(payload));
    });
    row.appendChild(submit); row.appendChild(err);
    wrap.appendChild(row);
    withDismiss(wrap);
    chat.appendChild(wrap);
    chat.scrollTop = chat.scrollHeight;
}
